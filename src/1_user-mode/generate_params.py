import numpy as np
import control as ct
import math

# ====================================================
# 1. 시뮬레이션 및 하드웨어 파라미터 & 평형점 설정
# ====================================================
dt = 0.002  # 샘플링 타임 (2ms)

# [물리적 하드웨어 스펙]
M = 5.0          # 구슬의 질량 (kg)
L = 0.01         # 인덕턴스 (H)
R = 1.0          # 저항 (Ohm)
g = 9.81         # 중력 가속도 (m/s^2)

# [동작점/평형점 설정]
y0 = 0.01        # 기준 높이 (1cm)
x10 = y0
x20 = 0
x30 = math.sqrt(M * g * x10)

# [수식 기반의 시스템 동역학 (CT) 행렬 생성] - Jacobian Linearization
A = np.array([
    [0,             1,               0],
    [g/x10,         0,               -2 * math.sqrt(g / (M * x10))],
    [0,             0,               -R/L]
])

B = np.array([
    [0],
    [0],
    [1/L]
])

C = np.array([[1, 0, 0]])
D = np.array([[0]])

# ====================================================
# 2. 성능 사양 (Performance Specifications)
# ====================================================
# [제어기 사양]
Mp_c = 0.2    # 20% 오버슈트
ts_c = 0.5    # 0.5초 정착 시간

# [관측기 사양] (제어기보다 훨씬 빠르게)
Mp_o = 0.1    # 10% 오버슈트
ts_o = 0.1    # 0.1초 정착 시간

# ====================================================
# 3. 사양 기반 극점(Poles) 자동 계산 로직
# ====================================================
def calc_poles(Mp, ts, is_observer=False):
    zeta = -np.log(Mp) / np.sqrt(np.pi**2 + (np.log(Mp))**2)
    wn = 4 / (zeta * ts)  # 5% 정착 시간 기준 공식
    
    sigma = -zeta * wn
    wd = wn * np.sqrt(max(0, 1 - zeta**2))
    
    cp1 = complex(sigma, wd)
    cp2 = complex(sigma, -wd)
    cp3 = -5 * wn  # Non-dominant pole
    
    return [cp1, cp2, cp3]

p_s = calc_poles(Mp_c, ts_c)           # 제어기 CT 극점
op_s = calc_poles(Mp_o, ts_o, True)    # 관측기 CT 극점

# ====================================================
# 4. ZOH 이산화 및 이득 계산
# ====================================================
sys_c = ct.ss(A, B, C, D)
sys_d = sys_c.sample(dt, method='zoh')
G, H = sys_d.A, sys_d.B

# 극점을 Z-도메인으로 매핑 (z = e^(sT))
p_z = np.exp(np.array(p_s) * dt)
op_z = np.exp(np.array(op_s) * dt)

# 이득 행렬 계산
K = ct.place(G, H, p_z)
L = ct.place(G.T, C.T, op_z).T

# 피드포워드 게인(Nbar) 계산 (DT 버전)
Z_vec = np.array([[0], [0], [0], [1]])
mat1 = np.block([[G - np.eye(3), H], [C, np.zeros((1,1))]])
N_mat = np.linalg.inv(mat1) @ Z_vec
Nx = N_mat[0:3, 0]
Nu = N_mat[3, 0]
Nbar = Nu + np.dot(K[0], Nx)

# ====================================================
# 5. C 헤더 파일(.h) 자동 생성
# ====================================================
header_code = f"""// =========================================================
// Auto-generated by Python (generate_params.py)
// Specs -> Controller (Mp={Mp_c*100}%, ts={ts_c}s)
// Specs -> Observer   (Mp={Mp_o*100}%, ts={ts_o}s)
// Sampling Time: {dt} seconds
// =========================================================
#ifndef MATRIX_PARAMS_H
#define MATRIX_PARAMS_H

const double TS = {dt};

const double x10 = {x10:.8f};
const double x20 = {x20:.8f};
const double x30 = {x30:.8f};

const double G[3][3] = {{
    {{{G[0,0]:.8f}, {G[0,1]:.8f}, {G[0,2]:.8f}}},
    {{{G[1,0]:.8f}, {G[1,1]:.8f}, {G[1,2]:.8f}}},
    {{{G[2,0]:.8f}, {G[2,1]:.8f}, {G[2,2]:.8f}}}
}};
const double H[3] = {{{H[0,0]:.8f}, {H[1,0]:.8f}, {H[2,0]:.8f}}};
const double K[3] = {{{K[0,0]:.8f}, {K[0,1]:.8f}, {K[0,2]:.8f}}};
const double L[3] = {{{L[0,0]:.8f}, {L[1,0]:.8f}, {L[2,0]:.8f}}};
const double Nbar = {Nbar:.8f};

#endif
"""

with open("matrix_params.h", "w") as f:
    f.write(header_code)

print(f"✅ Success: matrix_params.h generated with dt={dt}s, Cont_ts={ts_c}s, Obs_ts={ts_o}s")
